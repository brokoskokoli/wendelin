/// The set of tools currently offered to the model (implemented by the
/// `ToolRegistry` in `wendelin_tools`).
abstract interface class ToolCatalog {
  /// Specs of all active tools, in stable order (prompt caching).
  List<ToolSpec> activeSpecs();

  /// The tool called [name], or `null` if unknown or inactive.
  Tool? lookup(String name);
}

/// Executes tool calls with policy, confirmation and validation
/// (implemented by the `ToolExecutor` in `wendelin_tools`).
abstract interface class ToolInvoker {
  /// Executes [calls] and reports progress.
  ///
  /// Contract (checked by `toolInvokerContract`):
  /// - For every call exactly one [ToolStarted] and, after it, exactly one
  ///   [ToolFinished]; [ConfirmationNeeded] in between if the user must
  ///   decide. Every tool call therefore gets a result for the model.
  /// - The stream closes after the last [ToolFinished]. Failures are
  ///   reported as error outcomes, never as stream errors.
  /// - Declined confirmations yield `ToolOutcome.declined()` (not an error)
  ///   and the tool is not executed.
  /// - Cancellation via `ctx.cancel`: open confirmations are resolved as
  ///   declined, no further tool is executed, and every not yet finished
  ///   call ends with `ToolOutcome.cancelled()` (an error outcome). A context
  ///   that is already cancelled executes nothing. A call whose tool really
  ///   completed keeps its real outcome (its effect has happened). This holds
  ///   for sequential and parallel invokers alike.
  /// - Outcomes generated by the invoker itself (`cancelled()`, `declined()`,
  ///   unknown tool, invalid arguments, policy denial) are passed on
  ///   unchanged: no data envelope, no truncation. Only content produced by
  ///   tools is wrapped/truncated.
  Stream<ToolInvocationEvent> invokeAll(
    List<ToolCallBlock> calls,
    ToolContext ctx,
  );
}

/// Optional capability of a [ToolInvoker]: tells the *effective* risk of a
/// call, i.e. what the invoker's policy will do with it (a `read`/`write`
/// tool the user or the integration made confirm-only counts as `external`).
/// The agent uses it to hold back everything that is effectively `external`
/// until a TEE answer is verified. An invoker without it is judged by the
/// static [Tool.risk].
abstract interface class ToolRiskAssessor {
  /// The risk level [tool] is treated as in [sessionId]; [foreignContent]
  /// tells that the run has seen foreign content (a tool with a network
  /// target then counts as confirm-only).
  RiskLevel effectiveRisk(
    Tool tool,
    String sessionId, {
    bool foreignContent = false,
  });
}

/// Optional capability of a [ToolInvoker]: locks the `external` tools of a
/// conversation (WP157, ADR 0023). The agent calls it when the receipt of a
/// TEE answer turns out red (also when the provider rolled out a new key).
/// The lock belongs to the session id, survives a rebuild of the engine and
/// an app restart, and ends with the conversation or a green recheck of the
/// provider.
abstract interface class SessionLockable {
  /// Denies every `external` tool for [sessionId] from now on; [profileId]
  /// is the provider whose answer failed (a green recheck of it lifts the
  /// lock). Idempotent.
  void lockExternal(String sessionId, {String? profileId});
}

/// Progress of [ToolInvoker.invokeAll].
sealed class ToolInvocationEvent {
  const ToolInvocationEvent(this.call);

  /// The call this event belongs to.
  final ToolCallBlock call;
}

/// Execution of [call] has started.
final class ToolStarted extends ToolInvocationEvent {
  /// Creates the event.
  const ToolStarted(super.call);

  @override
  String toString() => 'ToolStarted(${call.id})';
}

/// The user must confirm [call]. Answer with [respond]; the invoker waits
/// for [decision].
final class ConfirmationNeeded extends ToolInvocationEvent {
  /// Creates the event; the invoker keeps [decision] to await the answer.
  const ConfirmationNeeded(
    super.call,
    this.description,
    this.decision, {
    this.risk = RiskLevel.external,
    this.privateDetails = false,
  });

  /// The tool redacts its audit arguments ([AuditArgumentsRedactor]): the
  /// lines after the first of [description] are private text and must not
  /// reach the audit log.
  final bool privateDetails;

  /// German text for the confirmation card (`ToolConfirmation.confirmationText`).
  final String description;

  /// The *effective* risk level the runtime applied to this call: the
  /// tool's own level, raised by stricter policy overrides (a `write` tool
  /// the user wants confirmed is shown as `external`). The UI shows this,
  /// not `Tool.risk`.
  final RiskLevel risk;

  /// Completed with the user's answer. Prefer [respond], which never throws.
  final Completer<bool> decision;

  /// Whether an answer has already been given.
  bool get answered => decision.isCompleted;

  /// Answers the confirmation: `true` = execute, `false` = decline.
  ///
  /// Idempotent: the first answer wins, later calls are ignored. The invoker
  /// itself calls `respond(false)` when the run is cancelled.
  void respond(bool approved) {
    if (!decision.isCompleted) decision.complete(approved);
  }

  @override
  String toString() => 'ConfirmationNeeded(${call.id}, $description)';
}

/// [call] has finished with [outcome] after [duration].
final class ToolFinished extends ToolInvocationEvent {
  /// Creates the event.
  const ToolFinished(super.call, this.outcome, this.duration);

  /// The result (also for failures and declined confirmations).
  final ToolOutcome outcome;

  /// Execution time.
  final Duration duration;

  @override
  String toString() => 'ToolFinished(${call.id}, $outcome)';
}
