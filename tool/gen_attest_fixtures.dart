// Erzeugt app/integration_test/support/tee_fixtures.g.dart aus den TEE-Fixtures (WP43/WP47).
// Der Gerätetest kann keine Dateien des Rechners lesen; ein Test in app/test prüft, dass die
// erzeugte Datei zu den Fixtures passt. Aufruf: dart run tool/gen_attest_fixtures.dart
import 'dart:io';

const _files = {
  'gatewayAttestation': 'gateway_attestation.json',
  'collateralPcs': 'collateral_pcs.json',
  'receipt': 'receipt.json',
  'session': 'session.json',
};
const _nearFiles = {
  'nearReport': 'report.json',
  'nearCollateralModel': 'collateral_model.json',
  'nearCollateralGateway': 'collateral_gateway.json',
};
const nearFixtureDir = 'packages/wendelin_providers/test/fixtures/near';
const fixtureDir = 'packages/wendelin_providers/test/fixtures/tee';
const output = 'app/integration_test/support/tee_fixtures.g.dart';

/// Inhalt der erzeugten Datei.
String generate() {
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/gen_attest_fixtures.dart - do not edit.')
    ..writeln('// Source: $fixtureDir, $nearFixtureDir')
    ..writeln();
  final all = [
    for (final e in _files.entries) (e.key, '$fixtureDir/${e.value}', e.value),
    for (final e in _nearFiles.entries)
      (e.key, '$nearFixtureDir/${e.value}', 'near/${e.value}'),
  ];
  for (final (key, path, value) in all) {
    final text = File(path).readAsStringSync();
    if (text.contains("'''")) {
      throw StateError('$value enthält Anführungszeichen-Folge');
    }
    b
      ..writeln('/// `$value`.')
      ..writeln("const String $key =\n    r'''$text''';")
      ..writeln();
  }
  return '${b.toString().trimRight()}\n';
}

void main() {
  File(output).writeAsStringSync(generate());
  stdout.writeln('geschrieben: $output');
}
